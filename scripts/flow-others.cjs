// Ben, Gate, Organizer, Artist, Proof. Usage: node flow-others.cjs outDir
const { chromium } = require('playwright')
const fs = require('fs'), path = require('path')
const base = process.env.BASE_URL || 'http://localhost:5173/'
const out = process.argv[2]; fs.mkdirSync(out, { recursive: true })
const W = +(process.env.W || 390), H = +(process.env.H || 844)
;(async () => {
  const b = await chromium.launch()
  const ctx = await b.newContext({ viewport: { width: W, height: H }, deviceScaleFactor: 1, hasTouch: W < 900, isMobile: W < 900 })
  const p = await ctx.newPage()
  const errs = []
  p.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()) })
  p.on('pageerror', (e) => errs.push('pageerror: ' + e.message))
  let n = 0
  const shot = async (name) => { n++; await p.screenshot({ path: path.join(out, `${String(n).padStart(2, '0')}_${name}.png`) }) }
  const wait = (ms) => p.waitForTimeout(ms)
  const click = async (sel) => { await p.locator(sel).first().click() }
  const st = (fn) => p.evaluate(fn)
  await p.goto(base); await p.evaluate(() => localStorage.clear())
  await p.goto(base + '#/demo', { waitUntil: 'networkidle' }); await wait(500)
  await st(() => { const s = window.__demo.getState(); s.ensure('listed'); s.setRole('ben') }); await wait(900)
  await shot('ben_discover')
  await click('text=The Afterglow Tour'); await wait(900); await shot('ben_event')
  await click('text=See 1 fair resale'); await wait(1800); await shot('ben_offer')
  await click('text=Buy for $113.30'); await wait(800); await shot('ben_pay')
  await p.locator('[aria-label="Double-tap to confirm payment"]').dblclick(); await wait(3200); await shot('ben_swap')
  await wait(2600); await shot('ben_swap_done')
  await p.getByRole('button', { name: 'Done', exact: true }).last().click(); await wait(1200); await shot('ben_wallet')
  await st(() => window.__demo.getState().setRole('gate')); await wait(900); await shot('gate_early')
  await click('text=Jump to show night'); await wait(700); await shot('gate_ready')
  await click('text=Scan Ben'); await wait(700); await shot('gate_flying')
  await wait(900); await shot('gate_welcome')
  await wait(3400)
  await click('[aria-label="Offline mode"]'); await wait(600); await shot('gate_offline')
  await click('text=Screenshot'); await wait(1600); await shot('gate_expired')
  await wait(3400); await click('text=old ticket'); await wait(1600); await shot('gate_not_owner')
  await wait(3400); await click('text=Scan Ben'); await wait(1600); await shot('gate_used')
  await wait(3400); await click('[aria-label="Offline mode"]'); await wait(500)
  await st(() => window.__demo.getState().setRole('ben')); await wait(1200); await shot('ben_used')
  await click('text=Skip to after the show'); await wait(3400); await shot('ben_badge')
  await click('text=Add to Fan Pass'); await wait(900); await shot('ben_pass')
  await st(() => window.__demo.getState().setRole('organizer')); await wait(1500); await shot('org_dash')
  await p.mouse.move(W / 2, H / 2); await p.mouse.wheel(0, 600); await wait(700); await shot('org_dash_scrolled')
  await click('text=New show'); await wait(800); await shot('org_step1')
  await click('text=Next: Price'); await wait(500); await shot('org_step2')
  await click('text=Next: Rules'); await wait(500); await shot('org_step3')
  await click('text=Next: Where'); await wait(500); await shot('org_step4_ga')
  await click('role=tab[name="New York"]'); await wait(500); await shot('org_step4_ny')
  await click('text=Issue 20,000 tickets'); await wait(1300); await shot('org_issuing')
  await wait(2200); await shot('org_issued')
  await st(() => window.__demo.getState().setRole('artist')); await wait(3200); await shot('artist')
  await click('text=Festival model'); await wait(1200); await shot('artist_model')
  await st(() => window.__demo.getState().setRole('proof')); await wait(1000); await shot('proof')
  await click('[aria-label="Under the hood"]'); await wait(3300); await shot('proof_hood')
  await click('text=Resell at $400'); await wait(1500); await shot('proof_revert')
  await p.mouse.wheel(0, 900); await wait(600); await shot('proof_list')
  await click('text=Resale >> nth=0'); await wait(1600); await shot('proof_detail')
  console.log(errs.length ? 'ERRORS:\n' + errs.join('\n') : 'no console errors')
  await b.close()
})().catch((e) => { console.error('FLOW FAILED:', e.message); process.exit(1) })
