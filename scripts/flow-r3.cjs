// Round 3: resale-first marketplace, categories, Taylor sold out, new venues.
const { chromium } = require('playwright')
const fs = require('fs'), path = require('path')
const base = process.env.BASE_URL || 'http://localhost:5173/'
const out = process.argv[2]; fs.mkdirSync(out, { recursive: true })
const W = +(process.env.W || 390), H = +(process.env.H || 844)
;(async () => {
  const b = await chromium.launch()
  const ctx = await b.newContext({ viewport: { width: W, height: H }, hasTouch: true, isMobile: true })
  const p = await ctx.newPage()
  const errs = []
  p.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()) })
  p.on('pageerror', (e) => errs.push('pageerror: ' + e.message))
  p.on('response', (r) => { if (r.status() >= 400) errs.push(r.status() + ' ' + r.url()) })
  let n = 0
  const shot = async (name) => { n++; await p.screenshot({ path: path.join(out, `${String(n).padStart(2, '0')}_${name}.png`) }) }
  const wait = (ms) => p.waitForTimeout(ms)
  const btn = (name) => p.getByRole('button', { name }).last()
  const tab = (name) => p.getByRole('tab', { name }).last()
  const back = () => p.locator('[aria-label="Back"], button:has-text("Back")').last().click()
  const st = (fn, arg) => p.evaluate(fn, arg)
  const swapDone = () => p.locator('div.z-\\[80\\] button:has-text("Done")').click()
  const scroll = async (dy) => { await p.mouse.move(W / 2, H / 2); await p.mouse.wheel(0, dy); await wait(600) }
  await p.goto(base); await p.evaluate(() => localStorage.clear())
  await p.goto(base + '#/demo', { waitUntil: 'networkidle' }); await wait(1200)
  await shot('discover')
  await scroll(520); await shot('discover_resale_card'); await scroll(700); await shot('discover_upcoming'); await scroll(-3000)
  for (const c of ['Sports', 'Arts & Theater', 'Family', 'Concerts']) { await tab(c).click(); await wait(500); await shot('cat_' + c.replace(/\W+/g, '')) }
  await tab('All events').click(); await p.fill('[aria-label="Search events"]', 'mercedes'); await wait(500); await shot('search_mercedes')
  await p.click('[aria-label="Clear search"]'); await wait(400)
  await scroll(520); await p.locator('button:has-text("resale tickets from")').first().click(); await wait(1200); await shot('taylor_event')
  await scroll(600); await shot('taylor_event_resale'); await scroll(700); await shot('taylor_event_map')
  await p.locator('button:has-text("Buy fair resale")').last().click(); await wait(1500); await shot('offer')
  await scroll(600); await shot('offer_scrolled')
  await p.locator('button:has-text("Buy for")').last().click(); await wait(900); await shot('offer_pay')
  await p.locator('[aria-label="Double-tap to confirm payment"]').dblclick(); await wait(1600); await shot('swap_mid')
  await p.getByText('The seat is yours').waitFor(); await wait(900); await shot('swap_done')
  await swapDone(); await wait(1500); await shot('wallet_taylor')
  await btn('Done').click(); await wait(600)
  await p.getByRole('button', { name: 'Resale' }).last().click(); await wait(900); await shot('resale_buy')
  await scroll(900); await shot('resale_buy_scrolled'); await scroll(-3000)
  await tab('Sell a ticket').click(); await wait(600); await shot('resale_sell')
  await scroll(700); await shot('resale_sell_scrolled'); await scroll(-3000)
  await p.locator('button:has-text("Zach Bryan")').first().click(); await wait(1100); await shot('resell_zach')
  await p.locator('button:has-text("Max allowed")').last().click(); await wait(900); await shot('resell_zach_max')
  await scroll(500); await shot('resell_zach_scrolled')
  await p.locator('button:has-text("List for")').last().click(); await wait(1000); await shot('resell_listed')
  await p.locator('button:has-text("Simulate a verified buyer")').last().click()
  await p.getByText('Sold to a verified fan').first().waitFor(); await wait(900); await shot('swap_sold')
  await swapDone(); await wait(800); await shot('after_sold')
  await p.getByRole('button', { name: 'Discover' }).last().click(); await wait(500)
  for (const [c, name, key] of [['Arts & Theater', 'Hamilton', 'hamilton'], ['Sports', 'Atlanta United', 'atlutd'], ['Family', 'Monster Jam', 'monsterjam']]) {
    await tab(c).click(); await wait(400)
    await p.locator(`button:has-text("${name}")`).first().click(); await wait(1200); await shot(key + '_event')
    await scroll(650); await shot(key + '_map')
    await p.locator('button:has-text("Find tickets")').last().click(); await wait(1000); await shot(key + '_seats')
    await back(); await wait(500); await back(); await wait(700)
  }
  await tab('All events').click()
  // canonical flow: Maya sells the Bad Bunny seat, Ben buys it
  await st(() => window.__demo.getState().ensure('mayaBought'))
  await st(() => { const s = window.__demo.getState(); const t = s.tickets.find((x) => x.eventId === 'nova' && x.owner === 'maya'); s.setStack('maya', 'tickets', [{ name: 'resell', params: { id: t.id } }]) }); await wait(1200); await shot('maya_resell_nova')
  await st(() => window.__demo.getState().ensure('listed'))
  await st(() => { const s = window.__demo.getState(); s.setStack('ben', 'discover', [{ name: 'event', params: { id: 'nova' } }]); s.setRole('ben') }); await wait(1400); await shot('ben_nova_event')
  await scroll(500); await shot('ben_nova_resale')
  await p.locator('button:has-text("Buy fair resale")').last().click(); await wait(1500); await shot('ben_offer')
  console.log(errs.length ? 'ERRORS:\n' + errs.join('\n') : 'no console errors')
  await b.close()
})().catch((e) => { console.error('FLOW FAILED:', e.message.split('\n')[0]); process.exit(1) })
