// Walks Maya's whole journey on a 390x844 phone and screenshots every step.
const { chromium } = require('playwright')
const fs = require('fs')
const path = require('path')
const base = process.env.BASE_URL || 'http://localhost:5173/'
const out = process.argv[2]
const W = +(process.env.W || 390), H = +(process.env.H || 844)
fs.mkdirSync(out, { recursive: true })
;(async () => {
  const b = await chromium.launch()
  const ctx = await b.newContext({ viewport: { width: W, height: H }, deviceScaleFactor: 1, hasTouch: W < 900, isMobile: W < 900 })
  const p = await ctx.newPage()
  const errs = []
  p.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()) })
  p.on('pageerror', (e) => errs.push('pageerror: ' + e.message))
  let n = 0
  const shot = async (name) => { n++; await p.screenshot({ path: path.join(out, `${String(n).padStart(2, '0')}_${name}.png`) }) }
  const wait = (ms) => p.waitForTimeout(ms)
  const click = async (sel, opts) => { await p.locator(sel).first().click(opts) }
  await p.goto(base); await p.evaluate(() => localStorage.clear())
  await p.goto(base + '#/demo', { waitUntil: 'networkidle' }); await wait(900)
  await shot('welcome')
  await click('text=Continue with Passkey'); await wait(700); await shot('faceid')
  await wait(2800); await shot('verify_intro')
  await click('text=Start'); await wait(1700); await shot('doc_scan')
  await wait(1600); await shot('doc_done')
  await wait(1700); await shot('selfie')
  await wait(3200); await shot('verified')
  await click('text=Start exploring'); await wait(900); await shot('discover')
  await click('text=The Afterglow Tour'); await wait(900); await shot('event')
  await p.mouse.move(W / 2, H / 2); await p.mouse.wheel(0, 700); await wait(600); await shot('event_scrolled')
  await click('text=Join the fair queue'); await wait(1200); await shot('queue')
  await click('text=Simulate bot attack'); await wait(1300); await shot('bot_attack')
  await wait(5000); await shot('queue_done')
  await click('text=Choose seats'); await wait(900); await shot('seats')
  for (const s of [7, 5, 6, 8]) { await click(`[aria-label="Row F seat ${s}"]`); await wait(150) }
  await click('[aria-label="Row F seat 9"]'); await wait(250); await shot('seat_limit')
  for (const s of [5, 6, 8]) { await click(`[aria-label="Row F seat ${s}"]`); await wait(120) }
  await wait(600); await click('button:has-text("$100.00")'); await wait(800); await shot('pay_sheet')
  await p.locator('[aria-label="Double-tap to confirm payment"]').dblclick(); await wait(500); await shot('pay_auth')
  await wait(2200); await shot('purchased')
  await click('text=View in My Tickets'); await wait(1400); await shot('wallet_open')
  await click('text=Done'); await wait(900); await shot('wallet_stack')
  await click('text=NOVA BLOOM >> nth=0'); await wait(1100)
  await click('text=Resell'); await wait(900); await shot('resell')
  const thumb = p.locator('[role=slider]').first(); const bb = await thumb.boundingBox()
  await p.mouse.move(bb.x + bb.width / 2, bb.y + bb.height / 2); await p.mouse.down()
  for (let i = 1; i <= 20; i++) { await p.mouse.move(bb.x + bb.width / 2 + i * 13, bb.y + bb.height / 2); await wait(16) }
  await wait(200); await shot('resell_push_cap')
  await p.mouse.up(); await wait(900); await shot('resell_at_cap')
  await click('text=List for $110.00'); await wait(900); await shot('listed')
  await click('text=Simulate a verified buyer'); await wait(1700); await shot('swap_mid')
  await wait(2600); await shot('swap_done')
  await click('text=Done'); await wait(1000); await shot('wallet_after_sale')
  await click('text=THE VELVET HOURS >> nth=0'); await wait(1200); await shot('velvet_open')
  await click('text=Gift'); await wait(900); await shot('gift')
  await click('text=Back'); await wait(700)
  await click('text=Resell'); await wait(900); await shot('resale_locked')
  await click('text=Back'); await wait(700)
  await click('text=Skip to after tonight'); await wait(1500); await shot('celebration_mid')
  await wait(2200); await shot('celebration_done')
  await click('text=Add to Fan Pass'); await wait(1000); await shot('fan_pass')
  console.log(errs.length ? 'ERRORS:\n' + errs.join('\n') : 'no console errors')
  await b.close()
})().catch((e) => { console.error('FLOW FAILED:', e.message); process.exit(1) })
